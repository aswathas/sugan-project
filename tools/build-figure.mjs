// The bench: a heavy plate on four legs, with a groove, screws, a label plate
// and a ruler strip along the front edge.
function bench() {
  const out = [`<path class="iso-halo" d="${k.haloOf(PLATE, LEG_BOTTOM, PLATE_H, P)}"/>`];

  for (const [x, y] of byDepth(k.corners(PLATE, 14))) {
    out.push(S(k.cylinder(x, y, LEG / 2 + 2.4, LEG_BOTTOM, 3, P, 24), { tone: "lo" }));
    out.push(S(k.slabOf({ x: x - LEG / 2, y: y - LEG / 2, w: LEG, d: LEG, r: 1 }, LEG_BOTTOM + 3, LEG_TOP - LEG_BOTTOM - 3, P, 1.4, 0.5), { tone: "lo" }));
    out.push(S(k.slabOf({ x: x - LEG / 2 - 1.6, y: y - LEG / 2 - 1.6, w: LEG + 3.2, d: LEG + 3.2, r: 1.4 }, LEG_TOP - 5, 5, P, 1.2, 0.5), { tone: "lo" }));
    out.push(D([at([x, y, LEG_BOTTOM + 1.2])], { size: 0.5, tone: "lo" }));
  }

  out.push(S(k.slabOf(PLATE, -PLATE_H, PLATE_H, P, 8, 1.6), { tone: "lo" }));
  out.push(L(k.planOutline(k.insetPlan(PLATE, 5), 0, P), { tone: "lo" }));

  const screws = k.corners(PLATE, 9);
  out.push(L(screws.map(([x, y]) => k.ring(x, y, 2.4, 0, P, 18)).join(""), { tone: "lo" }));
  out.push(D(screws.map(([x, y]) => at([x, y, 0])), { size: 0.55 }));

  // the label plate, with three rule lines
  const label = { x: -96, y: 8, w: 44, d: 13, r: 1.5 };
  out.push(S(k.slabOf(label, 0, 1.2, P, 2.5, 0.4), { tone: "lo" }));
  out.push(L(k.planOutline(k.insetPlan(label, 2), 1.2, P), { tone: "faint" }));
  for (let i = 0; i < 3; i++) {
    out.push(L(k.lineOnTop([label.x + 5, label.y + 3 + i * 3.4], [label.x + label.w - 6 - i * 7, label.y + 3 + i * 3.4], 1.2, P), { tone: "faint" }));
  }
  out.push(D([at([label.x + 2.4, label.y + 2.4, 1.2]), at([label.x + label.w - 2.4, label.y + label.d - 2.4, 1.2])], { size: 0.45 }));

  // the ruler strip along the front edge
  const strip = { x: -104, y: PLATE.y + PLATE.d - 14, w: 196, d: 6, r: 1 };
  out.push(S(k.slabOf(strip, 0, 0.7, P, 2, 0.3), { tone: "lo", crease: "none" }));
  const ticks = k.topTicks(strip.x + 4, strip.x + strip.w - 4, 5, 5, strip.y + 0.9, 0.7, [2.2, 4.2], P);
  out.push(L(ticks.minor, { tone: "lo" }), L(ticks.major, { tone: "mid" }));
  out.push(D([at([strip.x + 2, strip.y + 3, 0.7]), at([strip.x + strip.w - 2, strip.y + 3, 0.7])], { size: 0.45 }));

  return out.join("");
}

// The rail the sheet and the capsule travel on.
function rail() {
  const out = [];
  for (const y of [-RAIL_Y, RAIL_Y]) {
    out.push(S(k.slabOf({ x: RAIL_FROM, y: y - 1.6, w: RAIL_TO - RAIL_FROM, d: 3.2, r: 1 }, 0, RAIL_H, P, 1.2, 0.4), { tone: "mid" }));
    out.push(D([RAIL_FROM + 8, RAIL_TO - 4].map((x) => at([x, y, RAIL_H])), { size: 0.45, tone: "lo" }));
  }
  // the end stop at the left, and the chute lip at the right
  out.push(S(k.slabOf({ x: RAIL_FROM - 5, y: -9, w: 5, d: 18, r: 1.4 }, 0, 7, P, 1.4, 0.5), { tone: "mid" }));
  out.push(D([at([RAIL_FROM - 2.5, -5, 7]), at([RAIL_FROM - 2.5, 5, 7])], { size: 0.45 }));
  out.push(S(k.slabOf({ x: RAIL_TO - 3, y: -9, w: 4, d: 18, r: 1.4 }, 0, 5, P, 1.4, 0.5), { tone: "lo" }));
  return out.join("");
}

// The press: two posts, a beam, and the head that comes down.
function press() {
  const out = [];
  for (const y of [-POST_Y, POST_Y]) {
    out.push(S(k.slabOf({ x: -4, y: y - 4, w: 8, d: 8, r: 1.4 }, 0, POST_H, P, 2.5, 0.7), { tone: "mid" }));
    out.push(S(k.slabOf({ x: -5.6, y: y - 5.6, w: 11.2, d: 11.2, r: 1.6 }, 0, 3, P, 2, 0.6), { tone: "lo" }));
    out.push(S(k.slabOf({ x: -5, y: y - 5, w: 10, d: 10, r: 1.6 }, POST_H - 3, 3, P, 2, 0.6), { tone: "lo" }));
    out.push(D([at([-2.5, y - 2.5, 3]), at([2.5, y + 2.5, 3])], { size: 0.45 }));
  }
  out.push(S(k.slabOf(BEAM, POST_H, BEAM_H, P, 3, 0.9), { tone: "mid" }));
  out.push(L(k.planOutline(k.insetPlan(BEAM, 2), POST_H + BEAM_H, P), { tone: "faint" }));
  out.push(D([at([BEAM.x + 2.4, BEAM.y + 2.4, POST_H + BEAM_H]), at([BEAM.x + BEAM.w - 2.4, BEAM.y + BEAM.d - 2.4, POST_H + BEAM_H])], { size: 0.45 }));
  return out.join("");
}

// The head, the die and the two bearing arms that ride the posts.
function head() {
  const out = [];
  out.push(S(k.slabOf(HEAD, HEAD_REST, HEAD_H, P, 3, 0.9), { tone: "mid" }));
  out.push(L(k.planOutline(k.insetPlan(HEAD, 2.6), HEAD_REST + HEAD_H, P), { tone: "faint" }));
  for (const y of [-POST_Y, POST_Y]) {
    const near = y < 0 ? -1 : 1;
    out.push(S(k.slabOf({ x: -3.5, y: y < 0 ? -13 : 9, w: 7, d: 8, r: 1.2 }, HEAD_REST + 4, 7, P, 1.6, 0.5), { tone: "lo" }));
    out.push(D([at([0, y + near * 9.5, HEAD_REST + 11])], { size: 0.45 }));
  }
  // the die: the one lit part, the part the reader watches
  out.push(S(k.cylinder(0, 0, DIE_R, HEAD_REST - DIE_H, DIE_H, P, 40, 0.8), { tone: "hi", lit: true }));
  out.push(L(k.ring(0, 0, DIE_R - 1.4, HEAD_REST - DIE_H, P, 40), { tone: "faint" }));
  return out.join("");
}

// The carriage that brings the sheet, and the sheet itself.
function carriage() {
  const out = [`<path class="iso-halo" d="${k.haloOf(k.insetPlan(CARRIAGE, 3), CARRIAGE_TOP, 0.1, P)}" style="filter:blur(4px)"/>`];
  out.push(S(k.slabOf(CARRIAGE, RAIL_H, CARRIAGE_H, P, 4, 0.8), { tone: "mid" }));
  out.push(L(k.planOutline(k.insetPlan(CARRIAGE, 4), CARRIAGE_TOP, P), { tone: "faint" }));
  out.push(D([-24, -6, 6, 24].map((x) => at([x, CARRIAGE.y + CARRIAGE.d - 3, CARRIAGE_TOP])), { size: 0.42, tone: "lo" }));
  for (const y of [-RAIL_Y, RAIL_Y]) {
    out.push(S(k.cylinder(0, y, 2.6, RAIL_H, 2.2, P, 20), { tone: "lo" }));
  }
  // the handle
  const handle = [CARRIAGE.x + CARRIAGE.w - 9, CARRIAGE.y + CARRIAGE.d + 3];
  out.push(S(k.slabOf({ x: handle[0] - 2, y: handle[1] - 1, w: 4, d: 5, r: 1 }, CARRIAGE_TOP - 3, 4, P, 1.4, 0.4), { tone: "mid" }));
  out.push(S(k.cylinder(handle[0], handle[1] + 1.6, 3, CARRIAGE_TOP - 3, 5, P, 20), { tone: "mid" }));
  out.push(L(k.knurl(handle[0], handle[1] + 1.6, 3, CARRIAGE_TOP - 3, CARRIAGE_TOP + 2, 18, P), { tone: "lo" }));
  // the sheet: the file, with its lines of text
  out.push(S(k.slabOf(SHEET, CARRIAGE_TOP, SHEET_H, P, 1.2, 0.3), { tone: "hi" }));
  for (let i = 0; i < 5; i++) {
    const y = SHEET.y + 2.6 + i * 2.9;
    out.push(L(k.lineOnTop([SHEET.x + 3, y], [SHEET.x + SHEET.w - 3 - (i % 2) * 6, y], CARRIAGE_TOP + SHEET_H, P), { tone: "faint" }));
  }
  return out.join("");
}

// The sealed capsule: what the sheet becomes.
function capsule() {
  const out = [];
  out.push(S(k.slabOf(CAPSULE, RAIL_H, CAPSULE_H, P, 2.4, 0.6), { tone: "hi" }));
  out.push(L(k.planOutline(k.insetPlan(CAPSULE, 1.6), RAIL_H + CAPSULE_H, P), { tone: "faint" }));
  for (const x of [-4.6, 4.6]) {
    out.push(S(k.slabOf({ x: x - 1.2, y: -4.7, w: 2.4, d: 9.4, r: 1.1 }, RAIL_H - 0.3, CAPSULE_H + 0.9, P, 1, 0.4), { tone: "lo" }));
  }
  out.push(D([at([0, 0, RAIL_H + CAPSULE_H])], { size: 0.5, tone: "mid" }));
  return out.join("");
}

// The key dial: which key the press uses.
function dial() {
  const out = [];
  const [x, y] = DIAL;
  out.push(S(k.slabOf({ x: x - DIAL_R - 4, y: y - 4, w: DIAL_R + 12, d: 8, r: 1.4 }, 0, 4, P, 1.6, 0.5), { tone: "mid" }));
  out.push(S(k.cylinder(x, y, DIAL_R, 4, DIAL_H - 4, P, 48, 0.9), { tone: "mid" }));
  out.push(L(k.knurl(x, y, DIAL_R, 4, DIAL_H - 0.4, 40, P, 0.4), { tone: "lo" }));
  out.push(S(k.cylinder(x, y, DIAL_R - 1.6, DIAL_H, 1.4, P, 48, 0.5), { tone: "hi" }));
  const ticks = k.radialTicks(x, y, DIAL_R - 3.4, 0, 30, DIAL_H + 1.4, [1.4, 3], P);
  out.push(L(ticks.minor, { tone: "lo" }), L(ticks.major, { tone: "mid" }));
  out.push(L(k.ring(x, y, 1.8, DIAL_H + 1.4, P, 20), { tone: "mid" }));
  return out.join("");
}

// The pointer on the dial: the key that is selected.
function pointer(turn) {
  const angle = (turn * 360 * Math.PI) / 180;
  const [x, y] = DIAL;
  const r = DIAL_R - 3.8;
  return k.lineOnTop([x - Math.sin(angle) * 1.4, y + Math.cos(angle) * 1.4], [x + Math.sin(angle) * r, y - Math.cos(angle) * r], DIAL_H + 1.6, P);
}

// The store: the hopper that only ever holds sealed capsules.
function hopper() {
  const out = [];
  const floor = { x: HOPPER.x, y: HOPPER.y, w: HOPPER.w, d: HOPPER.d, r: 2 };
  out.push(S(k.slabOf(floor, HOPPER_FLOOR - 2, 2, P, 1.4, 0.4), { tone: "lo" }));
  // far wall and the two sides
  out.push(S(k.slabOf({ x: HOPPER.x, y: HOPPER.y + HOPPER.d, w: HOPPER.w, d: HOPPER_WALL, r: 1 }, HOPPER_FLOOR, HOPPER_TOP - HOPPER_FLOOR, P, 1.6, 0.5), { tone: "mid" }));
  out.push(S(k.slabOf({ x: HOPPER.x + HOPPER.w - HOPPER_WALL, y: HOPPER.y, w: HOPPER_WALL, d: HOPPER.d, r: 1 }, HOPPER_FLOOR, HOPPER_TOP - HOPPER_FLOOR, P, 1.6, 0.5), { tone: "mid" }));
  out.push(S(k.slabOf({ x: HOPPER.x, y: HOPPER.y, w: HOPPER_WALL, d: HOPPER.d, r: 1 }, HOPPER_FLOOR, HOPPER_TOP - HOPPER_FLOOR, P, 1.6, 0.5), { tone: "mid" }));
  // the near wall is lower, so the capsule can drop in and the pile is seen
  out.push(S(k.slabOf({ x: HOPPER.x, y: HOPPER.y, w: HOPPER_WALL, d: HOPPER.d, r: 1 }, HOPPER_FLOOR, HOPPER_TOP - HOPPER_FLOOR, P, 1.6, 0.5), { tone: "mid" }));
  // the rim
  out.push(L(k.planOutline(k.insetPlan(floor, 1), HOPPER_TOP, P), { tone: "lo" }));
  out.push(D([
    at([HOPPER.x + 4, HOPPER.y + 4, HOPPER_TOP]),
    at([HOPPER.x + HOPPER.w - 4, HOPPER.y + 4, HOPPER_TOP]),
  ], { size: 0.45 }));
  return out.join("");
}

// The capsules already in the store.
function stored(count) {
  const out = [];
  for (let i = 0; i < count; i++) {
    const z = HOPPER_FLOOR + i * (CAPSULE_H + 0.4);
    const plan = { x: HOPPER.x + 8, y: -6, w: CAPSULE.w, d: CAPSULE.d, r: CAPSULE.r };
    out.push(S(k.slabOf(plan, z, CAPSULE_H, P, 2, 0.5), { tone: "hi" }));
    out.push(L(k.planOutline(k.insetPlan(plan, 1.4), z + CAPSULE_H, P), { tone: "faint" }));
  }
  return out.join("");
}

// The wire from the dial to the press: the control that drives it.
function wiring() {
  const out = [];
  out.push(
    k.wireSvg([DIAL[0] + DIAL_R - 2, DIAL[1], 4], [0, POST_Y - 4, 3], {
      via: [[DIAL[0] + DIAL_R + 6, DIAL[1] + 4, 3], [14, POST_Y - 6, 3]],
      tone: "lo",
      size: 1.1,
    })
  );
  return out.join("");
}

