// The anatomy figure for SecureShare: a bench-top sealing press.
//
// The object is the explanation. A sheet of paper is the file the sender
// picks. The press is the browser: a key is turned on the dial, the head comes
// down, and the sheet is consumed and pressed into a sealed capsule. The
// capsule slides along the rail and drops into the hopper, which is the
// server. The hopper only ever holds capsules; the sheet is gone.
//
// Built with the anatomy kit (github.com/wheresryan22/anatomy, MIT). The kit
// is vendored under tools/figure/kit so the figure can be rebuilt without it.
//
//   node tools/build-figure.mjs
//
